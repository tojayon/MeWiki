test("saves remote PDF files locally and keeps the existing source after a failed replacement", async ({ page }) => {
  await connect(page);
  await insert(page, "PDF 文档");
  const pdf = page.locator('[data-media-kind="pdf"]').last();
  const bytes = researchPdfFixture();
  await page.route("https://example.com/paper.pdf", route => route.fulfill({ status: 200, headers: { "Access-Control-Allow-Origin": "*", "Content-Type": "application/pdf", "Content-Length": String(bytes.length) }, body: bytes }));
  await pdf.getByLabel("PDF 文档网址", { exact: true }).fill("https://example.com/paper.pdf");
  await pdf.getByRole("button", { name: "使用链接", exact: true }).click();
  await expect(pdf.locator("canvas")).toBeVisible();
  const directory = path.join(root, "资料库");
  const client = new ResearchMediaClient((url, options) => fetch(new URL(String(url), page.url()), options));
  const asset = await client.upload(directory, new File([bytes], "远程报告.pdf", { type: "application/pdf" }));
  await page.route("**/api/research-library/media/remote", route => route.fulfill({ json: { id: "a".repeat(64), bytes: bytes.length, total: bytes.length, status: "complete", asset } }));
  await pdf.getByRole("button", { name: "下载并保存PDF 文档", exact: true }).click();
  await expect(pdf).toHaveAttribute("data-media-source", "asset");
  await expect(pdf.locator("canvas")).toBeVisible();
  await pdf.getByRole("button", { name: "替换PDF 文档", exact: true }).click();
  await pdf.getByLabel("选择PDF 文档文件", { exact: true }).setInputFiles({ name: "错误.pdf", mimeType: "application/pdf", buffer: Buffer.from("not a PDF") });
  await expect(pdf.getByRole("alert")).toContainText(/PDF|格式|文件/);
  await expect(pdf).toHaveAttribute("data-media-source", "asset");
  await expect(pdf.locator("canvas")).toBeVisible();
});
